MERGE INTO TGT.DIM_DISTRICT t
USING (
    SELECT DISTRICT_ID, DISTRICT_NAME FROM TMP.TMP_STORE_MASTER
    WHERE FILE_DATE = TO_DATE($fd)
    QUALIFY ROW_NUMBER() OVER (PARTITION BY DISTRICT_ID ORDER BY SRC_ROW_NUM) = 1
) s ON t.DISTRICT_ID = s.DISTRICT_ID
WHEN MATCHED AND t.DISTRICT_NAME IS DISTINCT FROM s.DISTRICT_NAME THEN
    UPDATE SET DISTRICT_NAME = s.DISTRICT_NAME, BATCH_ID = $batch, REC_UPDT_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN
    INSERT (DISTRICT_ID, DISTRICT_NAME, BATCH_ID) VALUES (s.DISTRICT_ID, s.DISTRICT_NAME, $batch);