UPDATE TGT.DIM_LOCN t
SET EFF_TO_DT = DATEADD(day, -1, TO_DATE($fd)), CURR_FLG = 'N', BATCH_ID = $batch, REC_UPDT_TS = CURRENT_TIMESTAMP()
FROM (
    SELECT m.STORE_ID,
           MD5(CONCAT_WS('|', m.STORE_NAME, m.CITY, m.DISTRICT_ID)) AS ATTR_HASH
    FROM TMP.TMP_STORE_MASTER m
    WHERE m.FILE_DATE = TO_DATE($fd)
) s
WHERE t.STORE_ID = s.STORE_ID AND t.CURR_FLG = 'Y' AND t.ATTR_HASH <> s.ATTR_HASH AND t.EFF_FROM_DT < TO_DATE($fd);

INSERT INTO TGT.DIM_LOCN
    (STORE_ID, STORE_NAME, CITY, DISTRICT_KY, DISTRICT_ID, ATTR_HASH, EFF_FROM_DT, EFF_TO_DT, CURR_FLG, BATCH_ID)
SELECT s.STORE_ID, s.STORE_NAME, s.CITY, s.DISTRICT_KY, s.DISTRICT_ID, s.ATTR_HASH,
       TO_DATE($fd), TO_DATE('9999-12-31'), 'Y', $batch
FROM (
    SELECT m.STORE_ID, m.STORE_NAME, m.CITY, d.DISTRICT_KY, m.DISTRICT_ID,
           MD5(CONCAT_WS('|', m.STORE_NAME, m.CITY, m.DISTRICT_ID)) AS ATTR_HASH
    FROM TMP.TMP_STORE_MASTER m
    JOIN TGT.DIM_DISTRICT d ON m.DISTRICT_ID = d.DISTRICT_ID
    WHERE m.FILE_DATE = TO_DATE($fd)
) s
WHERE NOT EXISTS (
    SELECT 1 FROM TGT.DIM_LOCN t
    WHERE t.STORE_ID = s.STORE_ID AND t.CURR_FLG = 'Y' AND t.ATTR_HASH = s.ATTR_HASH
);