UPDATE TGT.FCT_INVENTORY t
SET EFF_TO_DT = DATEADD(day, -1, TO_DATE($fd)), CURR_FLG = 'N', BATCH_ID = $batch, REC_UPDT_TS = CURRENT_TIMESTAMP()
WHERE t.CURR_FLG = 'Y' AND t.EFF_FROM_DT < TO_DATE($fd)
  AND NOT EXISTS (
    SELECT 1
    FROM (
        SELECT i.ITEM_KY, l.LOCN_KY,
               MD5(CONCAT_WS('|', s.ONHAND_QTY::VARCHAR, s.ONORDER_QTY::VARCHAR)) AS ATTR_HASH
        FROM TMP.TMP_INVENTORY_SNAPSHOT s
        JOIN TGT.DIM_ITEM i ON s.ITEM_ID = i.ITEM_ID AND TO_DATE($fd) BETWEEN i.EFF_FROM_DT AND i.EFF_TO_DT
        JOIN TGT.DIM_LOCN l ON s.STORE_ID = l.STORE_ID AND TO_DATE($fd) BETWEEN l.EFF_FROM_DT AND l.EFF_TO_DT
        WHERE s.FILE_DATE = TO_DATE($fd)
    ) x
    WHERE x.ITEM_KY = t.ITEM_KY AND x.LOCN_KY = t.LOCN_KY AND x.ATTR_HASH = t.ATTR_HASH
);

INSERT INTO TGT.FCT_INVENTORY
    (ITEM_KY, LOCN_KY, ONHAND_QTY, ONORDER_QTY, ATTR_HASH, EFF_FROM_DT, EFF_TO_DT, CURR_FLG, BATCH_ID)
SELECT x.ITEM_KY, x.LOCN_KY, x.ONHAND_QTY, x.ONORDER_QTY, x.ATTR_HASH,
       TO_DATE($fd), TO_DATE('9999-12-31'), 'Y', $batch
FROM (
    SELECT i.ITEM_KY, l.LOCN_KY, s.ONHAND_QTY, s.ONORDER_QTY,
           MD5(CONCAT_WS('|', s.ONHAND_QTY::VARCHAR, s.ONORDER_QTY::VARCHAR)) AS ATTR_HASH
    FROM TMP.TMP_INVENTORY_SNAPSHOT s
    JOIN TGT.DIM_ITEM i ON s.ITEM_ID = i.ITEM_ID AND TO_DATE($fd) BETWEEN i.EFF_FROM_DT AND i.EFF_TO_DT
    JOIN TGT.DIM_LOCN l ON s.STORE_ID = l.STORE_ID AND TO_DATE($fd) BETWEEN l.EFF_FROM_DT AND l.EFF_TO_DT
    WHERE s.FILE_DATE = TO_DATE($fd)
) x
WHERE NOT EXISTS (
    SELECT 1 FROM TGT.FCT_INVENTORY t
    WHERE t.ITEM_KY = x.ITEM_KY AND t.LOCN_KY = x.LOCN_KY AND t.ATTR_HASH = x.ATTR_HASH AND t.CURR_FLG = 'Y'
);