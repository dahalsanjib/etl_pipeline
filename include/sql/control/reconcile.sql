SELECT CHECK_NAME, EXPECTED, ACTUAL, IFF(EXPECTED = ACTUAL, 'PASS', 'FAIL') AS STATUS
FROM (
    SELECT 'ROWCOUNT_SALES' AS CHECK_NAME,
           (SELECT COUNT(*) FROM STG.STG_POS_SALES WHERE FILE_DATE = TO_DATE($fd)) AS EXPECTED,
           (SELECT COUNT(*) FROM TGT.FCT_SALES WHERE DAY_DT = TO_DATE($fd))
         + (SELECT COUNT(*) FROM CTL.C_REJ_TABLE WHERE FEED_NAME = 'pos_sales' AND FILE_DATE = TO_DATE($fd)) AS ACTUAL
    UNION ALL
    SELECT 'AMOUNT_SALES',
           (SELECT COALESCE(SUM(TRY_TO_NUMBER(NET_SALES_AMT)), 0) FROM STG.STG_POS_SALES WHERE FILE_DATE = TO_DATE($fd)),
           (SELECT COALESCE(SUM(NET_SALES_AMT), 0) FROM TGT.FCT_SALES WHERE DAY_DT = TO_DATE($fd))
         + (SELECT COALESCE(SUM(TRY_TO_NUMBER(RAW_ROW:NET_SALES_AMT::VARCHAR)), 0) FROM CTL.C_REJ_TABLE WHERE FEED_NAME = 'pos_sales' AND FILE_DATE = TO_DATE($fd))
    UNION ALL
    SELECT 'ORPHANS_SALES', 0,
           (SELECT COUNT(*) FROM TMP.TMP_POS_SALES WHERE FILE_DATE = TO_DATE($fd))
         - (SELECT COUNT(*) FROM TGT.FCT_SALES WHERE DAY_DT = TO_DATE($fd))
    UNION ALL
    SELECT 'FRESHNESS_SALES', 0,
           DATEDIFF(day, (SELECT MAX(DAY_DT) FROM TGT.FCT_SALES WHERE DAY_DT <= TO_DATE($fd)), TO_DATE($fd))
    UNION ALL
    SELECT 'DUPLICATES_SALES', 0,
           (SELECT COUNT(*) FROM (SELECT TXN_ID, TXN_LINE_NO FROM TGT.FCT_SALES WHERE DAY_DT = TO_DATE($fd) GROUP BY 1, 2 HAVING COUNT(*) > 1))
    UNION ALL
    SELECT 'ROWCOUNT_INVENTORY',
           (SELECT COUNT(*) FROM STG.STG_INVENTORY_SNAPSHOT WHERE FILE_DATE = TO_DATE($fd)),
           (SELECT COUNT(*) FROM TMP.TMP_INVENTORY_SNAPSHOT WHERE FILE_DATE = TO_DATE($fd))
         + (SELECT COUNT(*) FROM CTL.C_REJ_TABLE WHERE FEED_NAME = 'inventory_snapshot' AND FILE_DATE = TO_DATE($fd))
    UNION ALL
    SELECT 'POSITIONS_INVENTORY',
           (SELECT COUNT(*) FROM TMP.TMP_INVENTORY_SNAPSHOT WHERE FILE_DATE = TO_DATE($fd)),
           (SELECT COUNT(*) FROM TGT.FCT_INVENTORY WHERE EFF_FROM_DT <= TO_DATE($fd) AND EFF_TO_DT >= TO_DATE($fd))
    UNION ALL
    SELECT 'DUPLICATES_INVENTORY', 0,
           (SELECT COUNT(*) FROM (SELECT ITEM_KY, LOCN_KY FROM TGT.FCT_INVENTORY WHERE EFF_FROM_DT <= TO_DATE($fd) AND EFF_TO_DT >= TO_DATE($fd) GROUP BY 1, 2 HAVING COUNT(*) > 1))
)
ORDER BY CHECK_NAME;