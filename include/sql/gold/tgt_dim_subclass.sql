MERGE INTO TGT.DIM_SUBCLASS t
USING (
    SELECT SUBCLASS_ID, SUBCLASS_NAME FROM TMP.TMP_ITEM_MASTER
    WHERE FILE_DATE = TO_DATE($fd)
    QUALIFY ROW_NUMBER() OVER (PARTITION BY SUBCLASS_ID ORDER BY SRC_ROW_NUM) = 1
) s ON t.SUBCLASS_ID = s.SUBCLASS_ID
WHEN MATCHED AND t.SUBCLASS_NAME IS DISTINCT FROM s.SUBCLASS_NAME THEN
    UPDATE SET SUBCLASS_NAME = s.SUBCLASS_NAME, BATCH_ID = $batch, REC_UPDT_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN
    INSERT (SUBCLASS_ID, SUBCLASS_NAME, BATCH_ID) VALUES (s.SUBCLASS_ID, s.SUBCLASS_NAME, $batch);