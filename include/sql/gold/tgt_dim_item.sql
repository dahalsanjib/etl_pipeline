UPDATE TGT.DIM_ITEM t
SET EFF_TO_DT = DATEADD(day, -1, TO_DATE($fd)), CURR_FLG = 'N', BATCH_ID = $batch, REC_UPDT_TS = CURRENT_TIMESTAMP()
FROM (
    SELECT m.ITEM_ID,
           MD5(CONCAT_WS('|', m.ITEM_NAME, m.SUBCLASS_ID, m.BRAND, m.UNIT_COST::VARCHAR, m.UNIT_PRICE::VARCHAR, m.STATUS)) AS ATTR_HASH
    FROM TMP.TMP_ITEM_MASTER m
    WHERE m.FILE_DATE = TO_DATE($fd)
) s
WHERE t.ITEM_ID = s.ITEM_ID AND t.CURR_FLG = 'Y' AND t.ATTR_HASH <> s.ATTR_HASH AND t.EFF_FROM_DT < TO_DATE($fd);

INSERT INTO TGT.DIM_ITEM
    (ITEM_ID, ITEM_NAME, SUBCLASS_KY, SUBCLASS_ID, BRAND, UNIT_COST, UNIT_PRICE, STATUS, ATTR_HASH,
     EFF_FROM_DT, EFF_TO_DT, CURR_FLG, BATCH_ID)
SELECT s.ITEM_ID, s.ITEM_NAME, s.SUBCLASS_KY, s.SUBCLASS_ID, s.BRAND, s.UNIT_COST, s.UNIT_PRICE, s.STATUS, s.ATTR_HASH,
       TO_DATE($fd), TO_DATE('9999-12-31'), 'Y', $batch
FROM (
    SELECT m.ITEM_ID, m.ITEM_NAME, sc.SUBCLASS_KY, m.SUBCLASS_ID, m.BRAND, m.UNIT_COST, m.UNIT_PRICE, m.STATUS,
           MD5(CONCAT_WS('|', m.ITEM_NAME, m.SUBCLASS_ID, m.BRAND, m.UNIT_COST::VARCHAR, m.UNIT_PRICE::VARCHAR, m.STATUS)) AS ATTR_HASH
    FROM TMP.TMP_ITEM_MASTER m
    JOIN TGT.DIM_SUBCLASS sc ON m.SUBCLASS_ID = sc.SUBCLASS_ID
    WHERE m.FILE_DATE = TO_DATE($fd)
) s
WHERE NOT EXISTS (
    SELECT 1 FROM TGT.DIM_ITEM t
    WHERE t.ITEM_ID = s.ITEM_ID AND t.CURR_FLG = 'Y' AND t.ATTR_HASH = s.ATTR_HASH
);