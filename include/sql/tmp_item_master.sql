USE DATABASE RETAIL_DW;

SET fd = '2026-11-15';
SET batch = 'MANUAL_TEST';

DELETE FROM TMP.TMP_ITEM_MASTER WHERE FILE_DATE = TO_DATE($fd);
DELETE FROM CTL.C_REJ_TABLE WHERE FEED_NAME = 'item_master' AND FILE_DATE = TO_DATE($fd);

INSERT ALL
    WHEN REASON_CODE IS NULL THEN
        INTO TMP.TMP_ITEM_MASTER
            (ITEM_ID, ITEM_NAME, SUBCLASS_ID, SUBCLASS_NAME, BRAND, UNIT_COST, UNIT_PRICE, STATUS,
             SRC_FILE_NM, FILE_DATE, SRC_ROW_NUM, BATCH_ID)
        VALUES
            (ITEM_ID, ITEM_NAME, SUBCLASS_ID, SUBCLASS_NAME, BRAND, COST_N, PRICE_N, STATUS,
             SRC_FILE_NM, FILE_DATE, SRC_ROW_NUM, BATCH_ID)
    WHEN REASON_CODE IS NOT NULL THEN
        INTO CTL.C_REJ_TABLE
            (FEED_NAME, SRC_FILE_NM, FILE_DATE, SRC_ROW_NUM, RULE_ID, REASON_CODE, RAW_ROW, ROW_HASH, BATCH_ID)
        VALUES
            (FEED_NAME, SRC_FILE_NM, FILE_DATE, SRC_ROW_NUM, RULE_ID, REASON_CODE, RAW_ROW, MD5(TO_VARCHAR(RAW_ROW)), BATCH_ID)
SELECT
    c.*,
    CASE
        WHEN c.REASON_CODE IN ('NULL_ITEM_ID', 'NULL_SUBCLASS_ID') THEN 'R2'
        WHEN c.REASON_CODE = 'INVALID_VALUE' THEN 'R3'
        WHEN c.REASON_CODE = 'NEGATIVE_AMOUNT' THEN 'R5'
        WHEN c.REASON_CODE = 'DUPLICATE_KEY' THEN 'R6'
    END AS RULE_ID
FROM (
    SELECT
        b.*,
        CASE
            WHEN b.ITEM_ID IS NULL THEN 'NULL_ITEM_ID'
            WHEN b.SUBCLASS_ID IS NULL THEN 'NULL_SUBCLASS_ID'
            WHEN b.COST_N IS NULL OR b.PRICE_N IS NULL THEN 'INVALID_VALUE'
            WHEN b.COST_N < 0 OR b.PRICE_N < 0 THEN 'NEGATIVE_AMOUNT'
            WHEN ROW_NUMBER() OVER (PARTITION BY b.ITEM_ID ORDER BY b.SRC_ROW_NUM) > 1 THEN 'DUPLICATE_KEY'
        END AS REASON_CODE
    FROM (
        SELECT
            'item_master' AS FEED_NAME,
            $batch AS BATCH_ID,
            s.SRC_FILE_NM,
            s.FILE_DATE,
            s.SRC_ROW_NUM,
            UPPER(NULLIF(TRIM(s.ITEM_ID), '')) AS ITEM_ID,
            TRIM(s.ITEM_NAME) AS ITEM_NAME,
            UPPER(NULLIF(TRIM(s.SUBCLASS_ID), '')) AS SUBCLASS_ID,
            TRIM(s.SUBCLASS_NAME) AS SUBCLASS_NAME,
            TRIM(s.BRAND) AS BRAND,
            TRY_TO_NUMBER(TRIM(s.UNIT_COST), 12, 2) AS COST_N,
            TRY_TO_NUMBER(TRIM(s.UNIT_PRICE), 12, 2) AS PRICE_N,
            UPPER(TRIM(s.STATUS)) AS STATUS,
            OBJECT_CONSTRUCT(
                'ITEM_ID', s.ITEM_ID, 'ITEM_NAME', s.ITEM_NAME, 'SUBCLASS_ID', s.SUBCLASS_ID,
                'SUBCLASS_NAME', s.SUBCLASS_NAME, 'BRAND', s.BRAND, 'UNIT_COST', s.UNIT_COST,
                'UNIT_PRICE', s.UNIT_PRICE, 'STATUS', s.STATUS
            ) AS RAW_ROW
        FROM STG.STG_ITEM_MASTER s
        WHERE s.FILE_DATE = TO_DATE($fd)
    ) b
) c;