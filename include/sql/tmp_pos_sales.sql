USE DATABASE RETAIL_DW;

SET fd = '2026-11-15';
SET batch = 'MANUAL_TEST';

DELETE FROM TMP.TMP_POS_SALES WHERE FILE_DATE = TO_DATE($fd);
DELETE FROM CTL.C_REJ_TABLE WHERE FEED_NAME = 'pos_sales' AND FILE_DATE = TO_DATE($fd);

INSERT ALL
    WHEN REASON_CODE IS NULL THEN
        INTO TMP.TMP_POS_SALES
            (TXN_ID, TXN_LINE_NO, TXN_DATE, STORE_ID, ITEM_ID, QTY, UNIT_PRICE, DISCOUNT_AMT,
             NET_SALES_AMT, SRC_FILE_NM, FILE_DATE, SRC_ROW_NUM, BATCH_ID)
        VALUES
            (TXN_ID, LINE_N, TXN_D, STORE_ID, ITEM_ID, QTY_N, PRICE_N, DISC_N,
             NET_N, SRC_FILE_NM, FILE_DATE, SRC_ROW_NUM, BATCH_ID)
    WHEN REASON_CODE IS NOT NULL THEN
        INTO CTL.C_REJ_TABLE
            (FEED_NAME, SRC_FILE_NM, FILE_DATE, SRC_ROW_NUM, RULE_ID, REASON_CODE, RAW_ROW, ROW_HASH, BATCH_ID)
        VALUES
            (FEED_NAME, SRC_FILE_NM, FILE_DATE, SRC_ROW_NUM, RULE_ID, REASON_CODE, RAW_ROW, MD5(TO_VARCHAR(RAW_ROW)), BATCH_ID)
SELECT
    c.*,
    CASE
        WHEN c.REASON_CODE IN ('NULL_TXN_KEY', 'NULL_STORE_ID', 'NULL_ITEM_ID') THEN 'R2'
        WHEN c.REASON_CODE = 'INVALID_VALUE' THEN 'R3'
        WHEN c.REASON_CODE IN ('ITEM_NOT_IN_MASTER', 'UNKNOWN_STORE') THEN 'R4'
        WHEN c.REASON_CODE IN ('NEGATIVE_QTY', 'ZERO_QTY', 'NEGATIVE_PRICE', 'NEGATIVE_DISCOUNT',
                               'DISCOUNT_TOO_HIGH', 'NET_MISMATCH', 'TXN_DATE_MISMATCH') THEN 'R5'
        WHEN c.REASON_CODE = 'DUPLICATE_LINE' THEN 'R6'
    END AS RULE_ID
FROM (
    SELECT
        b.*,
        CASE
            WHEN b.TXN_ID IS NULL OR b.LINE_RAW IS NULL THEN 'NULL_TXN_KEY'
            WHEN b.STORE_ID IS NULL THEN 'NULL_STORE_ID'
            WHEN b.ITEM_ID IS NULL THEN 'NULL_ITEM_ID'
            WHEN b.LINE_N IS NULL OR b.TXN_D IS NULL OR b.QTY_N IS NULL OR b.PRICE_N IS NULL
                 OR b.DISC_N IS NULL OR b.NET_N IS NULL THEN 'INVALID_VALUE'
            WHEN i.ITEM_ID IS NULL THEN 'ITEM_NOT_IN_MASTER'
            WHEN st.STORE_ID IS NULL THEN 'UNKNOWN_STORE'
            WHEN b.QTY_N < 0 THEN 'NEGATIVE_QTY'
            WHEN b.QTY_N = 0 THEN 'ZERO_QTY'
            WHEN b.PRICE_N < 0 THEN 'NEGATIVE_PRICE'
            WHEN b.DISC_N < 0 THEN 'NEGATIVE_DISCOUNT'
            WHEN b.DISC_N > b.QTY_N * b.PRICE_N THEN 'DISCOUNT_TOO_HIGH'
            WHEN b.NET_N <> b.QTY_N * b.PRICE_N - b.DISC_N THEN 'NET_MISMATCH'
            WHEN b.TXN_D <> b.FILE_DATE THEN 'TXN_DATE_MISMATCH'
            WHEN ROW_NUMBER() OVER (PARTITION BY b.TXN_ID, b.LINE_N ORDER BY b.SRC_ROW_NUM) > 1 THEN 'DUPLICATE_LINE'
        END AS REASON_CODE
    FROM (
        SELECT
            'pos_sales' AS FEED_NAME,
            $batch AS BATCH_ID,
            s.SRC_FILE_NM,
            s.FILE_DATE,
            s.SRC_ROW_NUM,
            UPPER(NULLIF(TRIM(s.TXN_ID), '')) AS TXN_ID,
            UPPER(NULLIF(TRIM(s.STORE_ID), '')) AS STORE_ID,
            UPPER(NULLIF(TRIM(s.ITEM_ID), '')) AS ITEM_ID,
            NULLIF(TRIM(s.TXN_LINE_NO), '') AS LINE_RAW,
            TRY_TO_NUMBER(TRIM(s.TXN_LINE_NO)) AS LINE_N,
            TRY_TO_DATE(TRIM(s.TXN_DATE)) AS TXN_D,
            TRY_TO_NUMBER(TRIM(s.QTY)) AS QTY_N,
            TRY_TO_NUMBER(TRIM(s.UNIT_PRICE), 12, 2) AS PRICE_N,
            TRY_TO_NUMBER(TRIM(s.DISCOUNT_AMT), 12, 2) AS DISC_N,
            TRY_TO_NUMBER(TRIM(s.NET_SALES_AMT), 14, 2) AS NET_N,
            OBJECT_CONSTRUCT(
                'TXN_ID', s.TXN_ID, 'TXN_LINE_NO', s.TXN_LINE_NO, 'TXN_DATE', s.TXN_DATE,
                'STORE_ID', s.STORE_ID, 'ITEM_ID', s.ITEM_ID, 'QTY', s.QTY,
                'UNIT_PRICE', s.UNIT_PRICE, 'DISCOUNT_AMT', s.DISCOUNT_AMT, 'NET_SALES_AMT', s.NET_SALES_AMT
            ) AS RAW_ROW
        FROM STG.STG_POS_SALES s
        WHERE s.FILE_DATE = TO_DATE($fd)
    ) b
    LEFT JOIN (
        SELECT DISTINCT ITEM_ID FROM TMP.TMP_ITEM_MASTER WHERE FILE_DATE = TO_DATE($fd)
    ) i ON b.ITEM_ID = i.ITEM_ID
    LEFT JOIN (
        SELECT DISTINCT STORE_ID FROM TMP.TMP_STORE_MASTER
        WHERE FILE_DATE = (SELECT MAX(FILE_DATE) FROM TMP.TMP_STORE_MASTER WHERE FILE_DATE <= TO_DATE($fd))
    ) st ON b.STORE_ID = st.STORE_ID
) c;