USE DATABASE RETAIL_DW;

SET fd = '2026-11-15';
SET batch = 'MANUAL_TEST';

DELETE FROM TMP.TMP_INVENTORY_SNAPSHOT WHERE FILE_DATE = TO_DATE($fd);
DELETE FROM CTL.C_REJ_TABLE WHERE FEED_NAME = 'inventory_snapshot' AND FILE_DATE = TO_DATE($fd);

INSERT ALL
    WHEN REASON_CODE IS NULL THEN
        INTO TMP.TMP_INVENTORY_SNAPSHOT
            (SNAPSHOT_DATE, STORE_ID, ITEM_ID, ONHAND_QTY, ONORDER_QTY, SRC_FILE_NM, FILE_DATE, SRC_ROW_NUM, BATCH_ID)
        VALUES
            (SNAP_D, STORE_ID, ITEM_ID, ONH_N, ONO_N, SRC_FILE_NM, FILE_DATE, SRC_ROW_NUM, BATCH_ID)
    WHEN REASON_CODE IS NOT NULL THEN
        INTO CTL.C_REJ_TABLE
            (FEED_NAME, SRC_FILE_NM, FILE_DATE, SRC_ROW_NUM, RULE_ID, REASON_CODE, RAW_ROW, ROW_HASH, BATCH_ID)
        VALUES
            (FEED_NAME, SRC_FILE_NM, FILE_DATE, SRC_ROW_NUM, RULE_ID, REASON_CODE, RAW_ROW, MD5(TO_VARCHAR(RAW_ROW)), BATCH_ID)
SELECT
    c.*,
    CASE
        WHEN c.REASON_CODE IN ('NULL_STORE_ID', 'NULL_ITEM_ID') THEN 'R2'
        WHEN c.REASON_CODE = 'INVALID_VALUE' THEN 'R3'
        WHEN c.REASON_CODE IN ('ITEM_NOT_IN_MASTER', 'UNKNOWN_STORE') THEN 'R4'
        WHEN c.REASON_CODE IN ('NEGATIVE_QTY', 'SNAPSHOT_DATE_MISMATCH') THEN 'R5'
        WHEN c.REASON_CODE = 'DUPLICATE_KEY' THEN 'R6'
    END AS RULE_ID
FROM (
    SELECT
        b.*,
        CASE
            WHEN b.STORE_ID IS NULL THEN 'NULL_STORE_ID'
            WHEN b.ITEM_ID IS NULL THEN 'NULL_ITEM_ID'
            WHEN b.SNAP_D IS NULL OR b.ONH_N IS NULL OR b.ONO_N IS NULL THEN 'INVALID_VALUE'
            WHEN i.ITEM_ID IS NULL THEN 'ITEM_NOT_IN_MASTER'
            WHEN st.STORE_ID IS NULL THEN 'UNKNOWN_STORE'
            WHEN b.ONH_N < 0 OR b.ONO_N < 0 THEN 'NEGATIVE_QTY'
            WHEN b.SNAP_D <> b.FILE_DATE THEN 'SNAPSHOT_DATE_MISMATCH'
            WHEN ROW_NUMBER() OVER (PARTITION BY b.STORE_ID, b.ITEM_ID, b.SNAP_D ORDER BY b.SRC_ROW_NUM) > 1 THEN 'DUPLICATE_KEY'
        END AS REASON_CODE
    FROM (
        SELECT
            'inventory_snapshot' AS FEED_NAME,
            $batch AS BATCH_ID,
            s.SRC_FILE_NM,
            s.FILE_DATE,
            s.SRC_ROW_NUM,
            UPPER(NULLIF(TRIM(s.STORE_ID), '')) AS STORE_ID,
            UPPER(NULLIF(TRIM(s.ITEM_ID), '')) AS ITEM_ID,
            TRY_TO_DATE(TRIM(s.SNAPSHOT_DATE)) AS SNAP_D,
            TRY_TO_NUMBER(TRIM(s.ONHAND_QTY)) AS ONH_N,
            TRY_TO_NUMBER(TRIM(s.ONORDER_QTY)) AS ONO_N,
            OBJECT_CONSTRUCT(
                'SNAPSHOT_DATE', s.SNAPSHOT_DATE, 'STORE_ID', s.STORE_ID, 'ITEM_ID', s.ITEM_ID,
                'ONHAND_QTY', s.ONHAND_QTY, 'ONORDER_QTY', s.ONORDER_QTY
            ) AS RAW_ROW
        FROM STG.STG_INVENTORY_SNAPSHOT s
        WHERE s.FILE_DATE = TO_DATE($fd)
    ) b
    LEFT JOIN (
        SELECT DISTINCT ITEM_ID FROM TMP.TMP_ITEM_MASTER WHERE FILE_DATE = TO_DATE($fd)
    ) i ON b.ITEM_ID = i.ITEM_ID
    LEFT JOIN (
        SELECT DISTINCT STORE_ID FROM TMP.TMP_STORE_MASTER
        WHERE FILE_DATE = (SELECT MAX(FILE_DATE) FROM TMP.TMP_STORE_MASTER WHERE FILE_DATE <= TO_DATE($fd))
    ) st ON b.STORE_ID = st.STORE_ID
) c;