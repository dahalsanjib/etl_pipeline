USE DATABASE RETAIL_DW;

SET fd = '2026-11-15';
SET batch = 'MANUAL_TEST';

DELETE FROM TMP.TMP_STORE_MASTER WHERE FILE_DATE = TO_DATE($fd);
DELETE FROM CTL.C_REJ_TABLE WHERE FEED_NAME = 'store_master' AND FILE_DATE = TO_DATE($fd);

INSERT ALL
    WHEN REASON_CODE IS NULL THEN
        INTO TMP.TMP_STORE_MASTER
            (STORE_ID, STORE_NAME, CITY, DISTRICT_ID, DISTRICT_NAME, SRC_FILE_NM, FILE_DATE, SRC_ROW_NUM, BATCH_ID)
        VALUES
            (STORE_ID, STORE_NAME, CITY, DISTRICT_ID, DISTRICT_NAME, SRC_FILE_NM, FILE_DATE, SRC_ROW_NUM, BATCH_ID)
    WHEN REASON_CODE IS NOT NULL THEN
        INTO CTL.C_REJ_TABLE
            (FEED_NAME, SRC_FILE_NM, FILE_DATE, SRC_ROW_NUM, RULE_ID, REASON_CODE, RAW_ROW, ROW_HASH, BATCH_ID)
        VALUES
            (FEED_NAME, SRC_FILE_NM, FILE_DATE, SRC_ROW_NUM, RULE_ID, REASON_CODE, RAW_ROW, MD5(TO_VARCHAR(RAW_ROW)), BATCH_ID)
SELECT
    c.*,
    CASE
        WHEN c.REASON_CODE IN ('NULL_STORE_ID', 'NULL_DISTRICT_ID') THEN 'R2'
        WHEN c.REASON_CODE = 'DUPLICATE_KEY' THEN 'R6'
    END AS RULE_ID
FROM (
    SELECT
        b.*,
        CASE
            WHEN b.STORE_ID IS NULL THEN 'NULL_STORE_ID'
            WHEN b.DISTRICT_ID IS NULL THEN 'NULL_DISTRICT_ID'
            WHEN ROW_NUMBER() OVER (PARTITION BY b.STORE_ID ORDER BY b.SRC_ROW_NUM) > 1 THEN 'DUPLICATE_KEY'
        END AS REASON_CODE
    FROM (
        SELECT
            'store_master' AS FEED_NAME,
            $batch AS BATCH_ID,
            s.SRC_FILE_NM,
            s.FILE_DATE,
            s.SRC_ROW_NUM,
            UPPER(NULLIF(TRIM(s.STORE_ID), '')) AS STORE_ID,
            TRIM(s.STORE_NAME) AS STORE_NAME,
            TRIM(s.CITY) AS CITY,
            UPPER(NULLIF(TRIM(s.DISTRICT_ID), '')) AS DISTRICT_ID,
            TRIM(s.DISTRICT_NAME) AS DISTRICT_NAME,
            OBJECT_CONSTRUCT(
                'STORE_ID', s.STORE_ID, 'STORE_NAME', s.STORE_NAME, 'CITY', s.CITY,
                'DISTRICT_ID', s.DISTRICT_ID, 'DISTRICT_NAME', s.DISTRICT_NAME
            ) AS RAW_ROW
        FROM STG.STG_STORE_MASTER s
        WHERE s.FILE_DATE = TO_DATE($fd)
    ) b
) c;