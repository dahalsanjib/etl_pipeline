DELETE FROM TGT.FCT_SALES WHERE DAY_DT = TO_DATE($fd);

INSERT INTO TGT.FCT_SALES
    (TXN_ID, TXN_LINE_NO, DAY_DT, ITEM_KY, LOCN_KY, QTY, UNIT_PRICE, DISCOUNT_AMT, NET_SALES_AMT, BATCH_ID)
SELECT s.TXN_ID, s.TXN_LINE_NO, s.TXN_DATE, i.ITEM_KY, l.LOCN_KY, s.QTY, s.UNIT_PRICE, s.DISCOUNT_AMT, s.NET_SALES_AMT, $batch
FROM TMP.TMP_POS_SALES s
JOIN TGT.DIM_ITEM i ON s.ITEM_ID = i.ITEM_ID AND s.TXN_DATE BETWEEN i.EFF_FROM_DT AND i.EFF_TO_DT
JOIN TGT.DIM_LOCN l ON s.STORE_ID = l.STORE_ID AND s.TXN_DATE BETWEEN l.EFF_FROM_DT AND l.EFF_TO_DT
WHERE s.FILE_DATE = TO_DATE($fd);