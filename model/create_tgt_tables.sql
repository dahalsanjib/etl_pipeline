INSERT INTO TGT.DIM_DATE (
    DATE_KEY, CALENDAR_DATE, DAY_OF_WEEK, DAY_NAME, DAY_OF_MONTH, DAY_OF_YEAR,
    ISO_WEEK, ISO_YEAR, ISO_WEEK_YEAR, ISO_WEEK_START_DATE, ISO_WEEK_END_DATE,
    MONTH, MONTH_NAME, QUARTER, YEAR, YEAR_MONTH, WEEKEND_FLAG, BATCH_ID
)
WITH date_spine AS (
    SELECT DATEADD(day, SEQ4(), '2020-01-01'::DATE) AS d
    FROM TABLE(GENERATOR(ROWCOUNT => 5844))
)
SELECT
    TO_NUMBER(TO_VARCHAR(d, 'YYYYMMDD')) AS DATE_KEY,
    d AS CALENDAR_DATE,
    DAYOFWEEKISO(d) AS DAY_OF_WEEK,
    DAYNAME(d) AS DAY_NAME,
    DAY(d) AS DAY_OF_MONTH,
    DAYOFYEAR(d) AS DAY_OF_YEAR,
    WEEKISO(d) AS ISO_WEEK,
    YEAROFWEEKISO(d) AS ISO_YEAR,
    CONCAT(YEAROFWEEKISO(d)::VARCHAR, '-W', LPAD(WEEKISO(d)::VARCHAR, 2, '0')) AS ISO_WEEK_YEAR,
    DATE_TRUNC('WEEK', d) AS ISO_WEEK_START_DATE,
    DATEADD(day, 6, DATE_TRUNC('WEEK', d)) AS ISO_WEEK_END_DATE,
    MONTH(d) AS MONTH,
    MONTHNAME(d) AS MONTH_NAME,
    QUARTER(d) AS QUARTER,
    YEAR(d) AS YEAR,
    TO_VARCHAR(d, 'YYYY-MM') AS YEAR_MONTH,
    IFF(DAYOFWEEKISO(d) IN (6, 7), 'Y', 'N') AS WEEKEND_FLAG,
    'STATIC_INIT' AS BATCH_ID
FROM date_spine
WHERE NOT EXISTS (SELECT 1 FROM TGT.DIM_DATE WHERE CALENDAR_DATE = d);

