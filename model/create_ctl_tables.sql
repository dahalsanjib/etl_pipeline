USE DATABASE RETAIL_DW;

CREATE SCHEMA IF NOT EXISTS CTL;

CREATE TABLE IF NOT EXISTS CTL.C_BATCH_LOG (
    BATCH_ID        VARCHAR,
    STEP_NAME       VARCHAR,
    SOURCE_NAME     VARCHAR,
    TARGET_NAME     VARCHAR,
    FILE_DATE       DATE,
    STATUS          VARCHAR,
    ROWS_READ       NUMBER,
    ROWS_LOADED     NUMBER,
    ROWS_REJECTED   NUMBER,
    START_TS        TIMESTAMP_NTZ,
    END_TS          TIMESTAMP_NTZ,
    ELAPSED_SEC     NUMBER(12,2),
    FAILURE_REASON  VARCHAR,
    REC_INS_TS      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CTL.C_REJ_TABLE (
    FEED_NAME     VARCHAR,
    SRC_FILE_NM   VARCHAR,
    FILE_DATE     DATE,
    SRC_ROW_NUM   NUMBER,
    RULE_ID       VARCHAR,
    REASON_CODE   VARCHAR,
    RAW_ROW       VARIANT,
    ROW_HASH      VARCHAR,
    BATCH_ID      VARCHAR,
    REC_INS_TS    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CTL.C_PARAM (
    BATCH_ID       VARCHAR,
    BUSINESS_DATE  DATE,
    RUN_TYPE       VARCHAR,
    CREATED_TS     TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CTL.C_LOAD_DATES (
    TARGET_NAME     VARCHAR,
    LAST_LOAD_DATE  DATE,
    BATCH_ID        VARCHAR,
    UPDATED_TS      TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CTL.C_BATCH_SCRIPTS (
    SCRIPT_NAME   VARCHAR,
    STEP_ORDER    NUMBER,
    TARGET_NAME   VARCHAR,
    ACTIVE_FLG    VARCHAR DEFAULT 'Y',
    REC_INS_TS    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

SHOW TABLES IN SCHEMA RETAIL_DW.CTL;
