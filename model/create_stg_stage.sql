USE WAREHOUSE COMPUTE_WH;
USE DATABASE RETAIL_DW;

CREATE FILE FORMAT IF NOT EXISTS STG.FF_SOURCE_CSV
    TYPE = 'CSV',
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    ENCODING = 'UTF8';

CREATE STAGE IF NOT EXISTS STG.STG_SOURCE_FILES
    FILE_FORMAT = STG.FF_SOURCE_CSV;

SHOW FILE FORMATS IN SCHEMA RETAIL_DW.STG;
SHOW STAGES IN SCHEMA RETAIL_DW.STG;RETAIL_DW.STG.STG_SOURCE_FILES